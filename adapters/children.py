#!/usr/bin/env python3
"""Report an enrolled parent's public child activity. This is cooperative reporting.

The parent credential never grants native-observer evidence or child command
authority. Text is passed on stdin; credentials are not printed or put in argv.
"""
import argparse
import json
from pathlib import Path
import sys
import urllib.error
import urllib.parse
import urllib.request


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


def endpoint(credential):
    value = urllib.parse.urlsplit(credential['endpoint'])
    if (value.scheme != 'http' or value.hostname not in {'127.0.0.1', 'localhost'}
            or value.username or value.password or value.query or value.fragment
            or value.path not in {'/api/agents/events', '/api/agents/inbox'}):
        raise ValueError('invalid_local_parent_credential')
    if not all(isinstance(credential.get(k), str) and credential[k] for k in ('agent_id', 'source_id', 'token')):
        raise ValueError('invalid_parent_credential')
    return urllib.parse.urlunsplit((value.scheme, value.netloc, '/api/agents/children/reports', '', ''))


def payload(args, credential, text=None):
    result = {'event_id': args.event_id, 'native_child_id': args.child_id,
              'native_parent_id': args.parent_id or credential['source_id'],
              'parent_run_id': args.parent_run, 'child_run_id': args.run,
              'type': {'start': 'started', 'message': 'message', 'complete': 'completed',
                       'fail': 'failed', 'cancel': 'cancelled'}[args.action]}
    if args.name:
        result['name'] = args.name
    if args.at:
        result['at'] = args.at
    if text is not None:
        if len(text) > 24000:
            raise ValueError('public_text_too_long')
        result['text'] = text
    if args.action == 'message':
        result['role'] = args.role
        result['phase'] = 'prompt' if args.role == 'user' else args.phase
    return result


def send(credential, event):
    request = urllib.request.Request(endpoint(credential),
        data=json.dumps(event, ensure_ascii=False, separators=(',', ':')).encode(), method='POST',
        headers={'Content-Type': 'application/json', 'X-Agent-Id': credential['agent_id'],
                 'Authorization': 'Bearer ' + credential['token']})
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    try:
        with opener.open(request, timeout=5) as response:
            body = response.read(65537)
            if len(body) > 65536:
                raise ValueError('invalid_child_receipt')
            value = json.loads(body)
            if not isinstance(value, dict):
                raise ValueError('invalid_child_receipt')
            return value
    except urllib.error.HTTPError as error:
        # No response bodies, URLs or request headers enter diagnostic output.
        return {'accepted': False, 'status': error.code, 'error': 'child_report_rejected'}


def parser():
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument('--credential', required=True)
    actions = result.add_subparsers(dest='action', required=True)
    for action in ('start', 'message', 'complete', 'fail', 'cancel'):
        command = actions.add_parser(action)
        command.add_argument('--child-id', required=True)
        command.add_argument('--parent-id')
        command.add_argument('--parent-run', required=True)
        command.add_argument('--run', required=True)
        command.add_argument('--event-id', required=True)
        command.add_argument('--name')
        command.add_argument('--at')
        command.add_argument('--text-stdin', action='store_true')
        command.add_argument('--role', choices=('user', 'assistant'), default='assistant')
        command.add_argument('--phase', choices=('commentary', 'final'), default='commentary')
    return result


def main():
    args = parser().parse_args()
    path = Path(args.credential).expanduser()
    if not path.is_file() or path.is_symlink() or path.stat().st_size > 16384:
        raise ValueError('parent_credential_unavailable')
    credential = json.loads(path.read_text())
    endpoint(credential)
    text = sys.stdin.read(24001) if args.text_stdin else None
    event = payload(args, credential, text)
    receipt = send(credential, event)
    # Native-observer claims are never generated by this cooperative client.
    allowed = {'accepted', 'duplicate', 'status', 'state', 'agent_id', 'run_id', 'error', 'evidence'}
    print(json.dumps({k: v for k, v in receipt.items() if k in allowed}, ensure_ascii=False))
    if not receipt.get('accepted'):
        raise SystemExit(1)


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, TypeError, KeyError, urllib.error.URLError):
        print(json.dumps({'accepted': False, 'error': 'child_reporting_unavailable'}), file=sys.stderr)
        raise SystemExit(1)
